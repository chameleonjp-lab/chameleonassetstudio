export function findNativeMotionStatusMessage(text: string): string | undefined {
  if (text === 'session boundary') return '編集や保存の操作に合わせて、表示確認を解除しました。';
  return NATIVE_MOTION_STATUS_MESSAGES.find((message) => message === text);
}

/** Return the catalog literal itself, never the caller-provided string. */
export function findNativeEditingMessage(text: string):
  | {
      code: NativeEditingMessageCode;
      reason: string;
    }
  | undefined {
  for (const [code, messages] of Object.entries(NATIVE_EDITING_FAILURE_MESSAGES)) {
    const reason = messages.find((message) => message === text);
    if (reason !== undefined) return { code: code as NativeEditingMessageCode, reason };
  }
  return undefined;
}

